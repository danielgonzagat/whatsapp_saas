// PR-276 anti-fraud allowlist for PULSE_* suffixes.
//
// Bypass markers (@ts-ignore, eslint-disable, biome-ignore, nosemgrep) are
// already banned by other gates. The PR-276 prompt mandates that the PULSE_*
// family also moves from blocklist (PULSE_OK, PULSE_SAFE, …) to allowlist of
// known legitimate suffixes — so a future agent cannot invent PULSE_NEWMADEUP
// as a fresh bypass marker and slip past the existing list.
//
// Run via `npm run guard:bypass-markers`. Exits non-zero on any unknown
// PULSE_<suffix> outside the allowlist.

