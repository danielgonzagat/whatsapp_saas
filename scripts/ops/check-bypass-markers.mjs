// Files that legitimately reference historical bypass markers as documentation
// (e.g. this very checker explaining what it bans).
const SELF_DOCUMENTING_FILES = new Set([
  'scripts/ops/check-bypass-markers.mjs',
  'scripts/ops/check-ai-constitution.mjs',
  'scripts/ops/collect-ratchet-metrics.mjs',
  'CLAUDE.md',
  'AGENTS.md',
  'docs/ai/PULSE_NO_HARDCODED_REALITY_DEBT_GUIDE.md',
]);

// File extensions that may contain PULSE_* identifiers in code.
const SCAN_EXTENSIONS = new Set(['.ts', '.tsx', '.js', '.jsx', '.mjs', '.cjs']);

// Directories we skip wholesale — generated/vendored or out-of-scope.
const SKIP_PREFIXES = [
  'node_modules/',
  '.git/',
  'dist/',
  'build/',
  '.next/',
  '.turbo/',
  'coverage/',
  'artifacts/',
];

const SKIP_REGEX = new RegExp(`^(?:${SKIP_PREFIXES.map((p) => p.replace('/', '\\/')).join('|')})`);

// Allow the artifact JSON files at repo root that legitimately store
// PULSE_* artifact names regenerated by the auditor itself.
const ALLOWED_ARTIFACT_FILES = new Set([
  'PULSE_CERTIFICATE.json',
  'PULSE_HEALTH.json',
  'PULSE_REPORT.md',
  'PULSE_WORLD_STATE.json',
  'PULSE_CLI_DIRECTIVE.json',
  'PULSE_ARTIFACT_INDEX.json',
  'PULSE_CODACY_STATE.json',
]);

const PULSE_TOKEN_RE = /\bPULSE_[A-Z][A-Z0-9_]*\b/g;

// Only line comments and block comments — that's where bypass markers live.
// `// PULSE_OK` or `/* PULSE_SAFE */`. PULSE_* identifiers in real code (env
// vars, file paths, type names) are not bypass markers and stay allowed.
const COMMENT_RE = /(?:\/\/[^\n]*|\/\*[\s\S]*?\*\/)/g;

function listFiles() {
  // Use git ls-files so we only scan tracked content; respects .gitignore.
  const stdout = execFileSync('git', ['ls-files', '-co', '--exclude-standard'], {
    cwd: repoRoot,
    encoding: 'utf8',
    stdio: ['ignore', 'pipe', 'ignore'],
  });
  return stdout
    .split('\n')
    .map((line) => line.trim())
    .filter((line) => line && !SKIP_REGEX.test(line));
}

function shouldScan(file) {
  if (ALLOWED_ARTIFACT_FILES.has(path.basename(file))) {
    return false;
  }
  const ext = path.extname(file).toLowerCase();
  return SCAN_EXTENSIONS.has(ext);
}

function readSafely(absolute) {
  try {
    const stat = statSync(absolute);
    if (!stat.isFile() || stat.size > 4 * 1024 * 1024) {
      return null;
    }
    return readFileSync(absolute, 'utf8');
  } catch {
    return null;
  }
}

function main() {
  const argFiles = process.argv.slice(2).filter(Boolean);
  const files = argFiles.length > 0 ? argFiles : listFiles().filter(shouldScan);

  const violations = [];

  for (const relative of files) {
    if (SELF_DOCUMENTING_FILES.has(relative)) {
      continue;
    }
    const absolute = path.isAbsolute(relative) ? relative : path.join(repoRoot, relative);
    const content = readSafely(absolute);
    if (content === null) {
      continue;
    }

    const lines = content.split('\n');

    // Match each comment block, then inspect its body for PULSE_* tokens.
    for (const commentMatch of content.matchAll(COMMENT_RE)) {
      const comment = commentMatch[0];
      const commentOffset = commentMatch.index ?? 0;
      for (const tokenMatch of comment.matchAll(PULSE_TOKEN_RE)) {
        const token = tokenMatch[0];
        if (ALLOWED_PULSE_SUFFIXES.has(token)) {
          continue;
        }
        const absoluteOffset = commentOffset + (tokenMatch.index ?? 0);
        const beforeOffset = content.slice(0, absoluteOffset);
        const lineNumber = beforeOffset.split('\n').length;
        const lineText = lines[lineNumber - 1] ?? '';
        violations.push(
          `${relative}:${lineNumber} :: unknown PULSE_* bypass marker ${token} :: ${lineText.trim()}`,
        );
      }
    }
  }

  if (violations.length > 0) {
    console.error(`[check-bypass-markers] ${violations.length} unknown PULSE_* token(s) detected:`);
    for (const violation of violations) {
      console.error(`- ${violation}`);
    }
    console.error('');
    console.error('PR-276 anti-fraud allowlist: every PULSE_* suffix must be declared in');
    console.error('ALLOWED_PULSE_SUFFIXES inside scripts/ops/check-bypass-markers.mjs.');
    console.error('Adding a new entry requires an ADR or explicit Daniel approval — never invent.');
    process.exit(1);
  }

  console.log(`[check-bypass-markers] OK — ${files.length} file(s) scanned, zero unknown PULSE_* tokens.`);
}

main();
